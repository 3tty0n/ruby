#!/usr/bin/env ruby
# frozen_string_literal: true

# Engineering-cost measurement: physical source lines of RPyYARV, of the
# CRuby patch it needs, and of the systems a reviewer would compare it with.

require "json"
require "fileutils"
require "time"

module Loc
  RPYYARV = File.expand_path("..", __dir__)
  ROOT = File.expand_path("../..", __dir__)
  UPSTREAM_TAG = "v4.0.6"

  # Extensions we can count, with their comment syntax.
  SYNTAX = {
    ".py" => { line: "#", block: nil, language: "python" },
    ".rb" => { line: "#", block: :ruby_document, language: "ruby" },
    ".c" => { line: "//", block: %w[/* */], language: "c" },
    ".h" => { line: "//", block: %w[/* */], language: "c" },
    ".rs" => { line: "//", block: %w[/* */], language: "rust" },
    ".java" => { line: "//", block: %w[/* */], language: "java" }
  }.freeze

  # First match wins; every remaining file lands in the "other" bucket.
  RPYYARV_COMPONENTS = [
    ["bytecode interpreter", %w[
      interp/execute.py interp/stackops.py interp/args.py interp/blocks.py
      interp/throws.py interp/defs.py interp/cref.py interp/supers.py
      interp/consts.py interp/consts_ids.py interp/builtins.py
      interp/evalsrc.py interp/callbacks.py interp/__init__.py
      block.py frame.py
    ]],
    ["instruction tables (generated by rpyvmgen)", %w[insns.py]],
    ["iseq loading and decoding", %w[
      iseq.py rawiseq.py bootiseq.py loader.py optable.py yarv_map.py
      iseqdump.py
    ]],
    ["method dispatch and sends", %w[interp/sends.py dispatch/*.py]],
    ["object model and values", %w[
      value.py objects/*.py to_a_layout.py classlib.py methods.py
      symbols.py error.py kernel.py
    ]],
    ["CRuby boundary (RPython side)", %w[
      boot/*.py rubycall.py requires.py rlib.py
    ]],
    ["CRuby boundary (C glue)", %w[boot_shim.c boot_shim.h]],
    ["core-library fast paths", %w[helpers/*.py]],
    ["GC bridge", %w[gcroots.py]],
    ["fiber integration", %w[fibers.py]],
    ["threads and ractors", %w[threading.py]],
    ["JIT entry points", %w[targetrpyyarv.py targetdump.py]],
    ["Ruby prelude", %w[prelude.py prelude.rb]],
    ["debugging and diagnostics", %w[debug.py]]
  ].freeze

  # Directories that are not RPyYARV's own implementation.
  RPYYARV_EXCLUDED = %w[
    test/ evaluation/ scripts/ benchmark/ awfy/ docs/ pypy/ ruby-bench/
    .bench-gems/ rpyvmgen/
  ].freeze

  # RPython JIT hints, counted separately as an informational figure.
  JIT_HINTS = /jit_merge_point|can_enter_jit|JitDriver|@elidable|
               unroll_safe|promote\(|hint\(|virtualizable/x

  # CRuby patch taxonomy, keyed by path prefix; first match wins.
  CRUBY_TAXONOMY = [
    ["rpyyarv.h", "new hook or API export"],
    ["vm_method.c", "new hook or API export"],
    ["variable.c", "new hook or API export"],
    ["class.c", "new hook or API export"],
    ["cont.c", "new hook or API export"],
    ["vm.c", "new hook or API export"],
    ["imemo.c", "garbage collector"],
    ["gc.c", "garbage collector"],
    ["proc.c", "VM call path"],
    ["vm_eval.c", "VM call path"],
    ["vm_insnhelper.c", "VM call path"],
    ["ractor.rb", "bug fix"],
    ["rpyvmgen/", "build system and tooling"],
    ["depend", "build system and tooling"],
    ["common.mk", "build system and tooling"],
    ["Makefile.in", "build system and tooling"],
    [".github/", "build system and tooling"]
  ].freeze

  module_function

  def counter_name
    @counter_name ||=
      system("command -v cloc > /dev/null 2>&1") ? "cloc" : "builtin"
  end

  def count_file(path)
    syntax = SYNTAX[File.extname(path)]
    return 0 unless syntax

    count_lines(File.read(path, encoding: "UTF-8", invalid: :replace,
                                undef: :replace), syntax)
  end

  # Non-blank, non-comment physical lines.  Python and Ruby docstrings are
  # counted as code, which is the conservative direction for our own totals.
  def count_lines(text, syntax)
    open, close = syntax[:block] if syntax[:block].is_a?(Array)
    document = syntax[:block] == :ruby_document
    inside = false
    lines = 0
    text.each_line do |raw|
      line = raw.strip
      if document
        inside = true if line.start_with?("=begin")
        if inside
          inside = false if line.start_with?("=end")
          next
        end
      elsif open
        line = strip_block(line, open, close, inside) { |state| inside = state }
      end
      next if line.empty?
      next if syntax[:line] && line.start_with?(syntax[:line])

      lines += 1
    end
    lines
  end

  def strip_block(line, open, close, inside)
    out = +""
    index = 0
    while index < line.length
      if inside
        stop = line.index(close, index)
        break unless stop

        inside = false
        index = stop + close.length
      else
        start = line.index(open, index)
        unless start
          out << line[index..]
          break
        end
        out << line[index...start]
        inside = true
        index = start + open.length
      end
    end
    yield inside
    out.strip
  end

  def language_of(path)
    (SYNTAX[File.extname(path)] || {})[:language] || "other"
  end

  def arch_specific?(path)
    !!(path =~ %r{(^|/|-)(x86_64|x86|arm64|aarch64)(/|-|\.|$)})
  end

  def row(system, component, language, files, lines, source,
          arch: false, added: nil, removed: nil)
    { "system" => system, "component" => component, "language" => language,
      "files" => files, "lines" => lines, "lines_added" => added,
      "lines_removed" => removed, "architecture_specific" => arch,
      "source" => source }
  end

  def git(dir, *args)
    output = IO.popen(["git", "-C", dir, *args], err: File::NULL, &:read)
    $?.success? ? output : nil
  end

  def commit_of(dir)
    (git(dir, "rev-parse", "HEAD") || "unknown").strip
  end

  # Files under dir matching the extensions, tracked-only when it is a repo.
  def source_files(dir, extensions)
    listed = git(dir, "ls-files")
    paths =
      if listed
        listed.split("\n")
      else
        Dir.glob("**/*", base: dir).select { |p| File.file?(File.join(dir, p)) }
      end
    paths.select { |p| extensions.include?(File.extname(p)) }
  end

  def sum(dir, paths)
    [paths.length, paths.sum { |p| count_file(File.join(dir, p)) }]
  end

  def rpyyarv_rows
    paths = source_files(RPYYARV, SYNTAX.keys).reject do |path|
      RPYYARV_EXCLUDED.any? { |prefix| path.start_with?(prefix) }
    end
    remaining = paths.dup
    rows = RPYYARV_COMPONENTS.map do |name, patterns|
      taken = remaining.select do |path|
        patterns.any? { |pattern| File.fnmatch?(pattern, path) }
      end
      remaining -= taken
      language = taken.map { |p| language_of(p) }.uniq
      files, lines = sum(RPYYARV, taken)
      row("rpyyarv", name, language.sort.join("+"), files, lines, "worktree")
    end
    unless remaining.empty?
      files, lines = sum(RPYYARV, remaining)
      rows << row("rpyyarv", "other", "python", files, lines,
                  remaining.sort.join(" "))
    end
    rows + [patch_row]
  end

  # RPython toolchain patches: lines this project adds to PyPy.
  def patch_row
    patches = Dir.glob(File.join(RPYYARV, "pypy-patches", "*.patch")).sort
    added = patches.sum do |patch|
      File.readlines(patch).count do |line|
        line.start_with?("+") && !line.start_with?("+++")
      end
    end
    arch = patches.count { |p| arch_specific?(File.basename(p)) }
    row("rpyyarv", "RPython toolchain patches", "diff", patches.length, added,
        "#{arch} of #{patches.length} patches are architecture specific",
        arch: arch.positive?)
  end

  def jit_hint_lines
    source_files(RPYYARV, [".py"]).reject { |path|
      RPYYARV_EXCLUDED.any? { |prefix| path.start_with?(prefix) }
    }.sum do |path|
      File.readlines(File.join(RPYYARV, path)).count { |l| l =~ JIT_HINTS }
    end
  end

  def base_commit
    (git(ROOT, "merge-base", "HEAD", UPSTREAM_TAG) || "").strip
  end

  def base_is_upstream?(base)
    return false if base.empty?

    tags = (git(ROOT, "tag", "--contains", base) || "").split("\n")
    tags.include?(UPSTREAM_TAG)
  end

  def cruby_rows(base)
    return [] if base.empty?

    stat = git(ROOT, "diff", "--numstat", base, "HEAD", "--", ".",
               ":(exclude)rpyyarv")
    buckets = Hash.new { |h, k| h[k] = [0, 0, 0] }
    stat.to_s.each_line do |line|
      added, removed, path = line.split("\t", 3)
      next unless path

      bucket = buckets[classify(path.strip)]
      bucket[0] += 1
      bucket[1] += added.to_i
      bucket[2] += removed.to_i
    end
    buckets.sort.map do |name, (files, added, removed)|
      row("cruby-patch", name, "c+ruby+build", files, added + removed,
          "diff #{base[0, 12]}..HEAD", added: added, removed: removed)
    end
  end

  def classify(path)
    found = CRUBY_TAXONOMY.find { |prefix, _| path.start_with?(prefix) }
    found ? found[1] : "other"
  end

  def jit_rows(name)
    dir = File.join(ROOT, name, "src")
    return [] unless File.directory?(dir)

    files = source_files(dir, [".rs"])
    generated, written = files.partition { |p| p.end_with?(".inc.rs") }
    arch, portable = written.partition { |p| arch_specific?(p) }
    rows = [
      ["#{name}/src (architecture independent)", portable, false],
      ["#{name}/src (architecture specific)", arch, true],
      ["#{name}/src (generated bindings)", generated, false]
    ].map do |component, paths, is_arch|
      count, lines = sum(dir, paths)
      row(name, component, "rust", count, lines, "worktree", arch: is_arch)
    end
    glue = %W[#{name}.c #{name}.h #{name}.rb].select do |file|
      File.file?(File.join(ROOT, file))
    end
    count, lines = sum(ROOT, glue)
    rows << row(name, "#{name}.c, #{name}.h, #{name}.rb", "c+ruby", count,
                lines, "worktree")
  end

  def external_rows(system, dir, parts)
    return [] unless dir && File.directory?(dir)

    commit = commit_of(dir)
    parts.filter_map do |component, subdir, extension|
      path = File.join(dir, subdir)
      next unless File.directory?(path)

      files, lines = sum(path, source_files(path, [extension]))
      row(system, component, SYNTAX[extension][:language], files, lines,
          "#{commit[0, 12]} #{subdir}")
    end
  end

  def truffleruby_rows(dir)
    external_rows("truffleruby", dir,
                  [["src/main/java (Java implementation)", "src/main/java",
                    ".java"],
                   ["src/main/ruby (Ruby core library)", "src/main/ruby",
                    ".rb"]])
  end

  def topaz_rows(dir)
    external_rows("topaz", dir,
                  [["topaz (RPython implementation)", "topaz", ".py"],
                   ["lib-ruby (Ruby core library)", "lib-ruby", ".rb"],
                   ["lib-topaz (Ruby prelude)", "lib-topaz", ".rb"]])
  end

  def self_check
    checks = {
      ".py" => ["# c\nx = 1\n\ny = 2  # t\n", 2],
      ".rb" => ["=begin\nc\n=end\nx = 1\n\n", 1],
      ".c" => ["/* a\n b */int x;\n// c\n\nint y; /* z */\n", 2],
      ".rs" => ["// c\nfn a() {}\n\n", 1],
      ".java" => ["/* c */\nclass A {}\n", 1]
    }
    checks.each do |extension, (text, expected)|
      got = count_lines(text, SYNTAX[extension])
      raise "#{extension}: expected #{expected}, got #{got}" unless got ==
                                                                    expected
    end
    puts "self-check ok (#{counter_name} counter)"
    0
  end

  def run(argv)
    out = nil
    truffleruby = nil
    topaz = nil
    until argv.empty?
      case (arg = argv.shift)
      when "--self-check" then return self_check
      when "--out" then out = argv.shift
      when "--truffleruby" then truffleruby = argv.shift
      when "--topaz" then topaz = argv.shift
      else
        warn "usage: loc.rb [--out DIR] [--truffleruby DIR] [--topaz DIR]" \
             " [--self-check]"
        return 1
      end
    end
    out ||= File.join(__dir__, "results",
                      Time.now.utc.strftime("%Y%m%dT%H%M%SZ-loc-") +
                      Process.pid.to_s)
    report(File.expand_path(out), truffleruby, topaz)
  end

  def report(out, truffleruby, topaz)
    base = base_commit
    notes = []
    notes << "truffleruby not counted: pass --truffleruby DIR" unless
      truffleruby
    notes << "topaz not counted: pass --topaz DIR" unless topaz
    unless base_is_upstream?(base)
      notes << "base commit is not contained in #{UPSTREAM_TAG}"
    end

    rows = rpyyarv_rows + cruby_rows(base) + jit_rows("yjit") +
           jit_rows("zjit") + truffleruby_rows(truffleruby) +
           topaz_rows(topaz)

    FileUtils.mkdir_p(out)
    File.write(File.join(out, "loc.json"),
               JSON.pretty_generate("rows" => rows) + "\n")
    write_csv(File.join(out, "loc.csv"), rows)
    manifest = {
      "generated_at" => Time.now.utc.iso8601,
      "commit" => commit_of(ROOT),
      "upstream_base_commit" => base,
      "upstream_base_tag" => UPSTREAM_TAG,
      "base_is_upstream" => base_is_upstream?(base),
      "counting_method" => counter_name,
      "counting_rule" => "physical lines that are neither blank nor a " \
                         "comment; docstrings count as code",
      "rpyyarv_jit_hint_lines" => jit_hint_lines,
      "truffleruby" => truffleruby && {
        "path" => truffleruby, "commit" => commit_of(truffleruby)
      },
      "topaz" => topaz && {
        "path" => topaz, "commit" => commit_of(topaz)
      },
      "notes" => notes
    }
    File.write(File.join(out, "manifest.json"),
               JSON.pretty_generate(manifest) + "\n")
    print_summary(rows, notes)
    puts "wrote #{out}"
    0
  end

  def write_csv(path, rows)
    headers = %w[system component language files lines lines_added
                 lines_removed architecture_specific source]
    File.open(path, "w") do |file|
      file.puts headers.join(",")
      rows.each do |data|
        file.puts headers.map { |key| csv_field(data[key]) }.join(",")
      end
    end
  end

  def csv_field(value)
    return "" if value.nil?

    text = value.to_s
    text.match?(/[",\n]/) ? %("#{text.gsub('"', '""')}") : text
  end

  def print_summary(rows, notes)
    width = rows.map { |r| r["component"].length }.max
    rows.group_by { |r| r["system"] }.each do |system, group|
      puts system
      group.each do |data|
        detail = if data["lines_added"]
                   format("+%d -%d", data["lines_added"],
                          data["lines_removed"])
                 else
                   ""
                 end
        puts format("  %-#{width}s %7d lines %5d files %s%s",
                    data["component"], data["lines"], data["files"], detail,
                    data["architecture_specific"] ? " [arch]" : "")
      end
      puts format("  %-#{width}s %7d lines", "total",
                  group.sum { |r| r["lines"] })
    end
    notes.each { |note| puts "note: #{note}" }
  end
end

exit(Loc.run(ARGV)) if $PROGRAM_NAME == __FILE__
