    C("CHECKMATCH_TYPE_WHEN", VM_CHECKMATCH_TYPE_WHEN);
    C("CHECKMATCH_TYPE_CASE", VM_CHECKMATCH_TYPE_CASE);
    C("CHECKMATCH_TYPE_RESCUE", VM_CHECKMATCH_TYPE_RESCUE);
    C("CHECKMATCH_ARRAY", VM_CHECKMATCH_ARRAY);
    C("NEWARRAY_SEND_MAX", VM_OPT_NEWARRAY_SEND_MAX);
    C("NEWARRAY_SEND_MIN", VM_OPT_NEWARRAY_SEND_MIN);
    C("NEWARRAY_SEND_HASH", VM_OPT_NEWARRAY_SEND_HASH);
    C("NEWARRAY_SEND_PACK", VM_OPT_NEWARRAY_SEND_PACK);
    C("NEWARRAY_SEND_PACK_BUFFER", VM_OPT_NEWARRAY_SEND_PACK_BUFFER);
    C("NEWARRAY_SEND_INCLUDE_P", VM_OPT_NEWARRAY_SEND_INCLUDE_P);

    /* vm_callinfo.h */
    C("CALL_FLAG_ARGS_SPLAT", VM_CALL_ARGS_SPLAT);
    C("CALL_FLAG_ARGS_BLOCKARG", VM_CALL_ARGS_BLOCKARG);
    C("CALL_FLAG_FCALL", VM_CALL_FCALL);
    C("CALL_FLAG_VCALL", VM_CALL_VCALL);
    C("CALL_FLAG_ARGS_SIMPLE", VM_CALL_ARGS_SIMPLE);
    C("CALL_FLAG_KWARG", VM_CALL_KWARG);
    C("CALL_FLAG_KW_SPLAT", VM_CALL_KW_SPLAT);
    C("CALL_FLAG_TAILCALL", VM_CALL_TAILCALL);
    C("CALL_FLAG_SUPER", VM_CALL_SUPER);
    C("CALL_FLAG_ZSUPER", VM_CALL_ZSUPER);
    C("CALL_FLAG_OPT_SEND", VM_CALL_OPT_SEND);
    C("CALL_FLAG_KW_SPLAT_MUT", VM_CALL_KW_SPLAT_MUT);
    C("CALL_FLAG_ARGS_SPLAT_MUT", VM_CALL_ARGS_SPLAT_MUT);
    C("CALL_FLAG_FORWARDING", VM_CALL_FORWARDING);

    /* iseq.h, enum defined_type */
