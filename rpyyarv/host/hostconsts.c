    C("DEFINED_GVAR", DEFINED_GVAR);
    C("DEFINED_CVAR", DEFINED_CVAR);
    C("DEFINED_CONST", DEFINED_CONST);
    C("DEFINED_METHOD", DEFINED_METHOD);
    C("DEFINED_YIELD", DEFINED_YIELD);
    C("DEFINED_FUNC", DEFINED_FUNC);
    C("DEFINED_CONST_FROM", DEFINED_CONST_FROM);
