/* Emit host/<version>/consts.py: each host constant RPyYARV compiles in,
   read from the host's own headers so a port never re-types one.
   Built and run by `make host`; the boot checks re-read the same macros
   from the linked libruby, so a stale description fails loudly. */
#include <stdio.h>
#include <stddef.h>
#include <ruby.h>
#include <ruby/version.h>
#include "internal.h"
#include "shape.h"
#include "internal/array.h"
